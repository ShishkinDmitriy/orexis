"""A grid's adjacency: what onboarding derives of a world whose cells state coordinates and no edges.

**A drive reads adjacency, and a geometry is what writes it.** The courier's drive takes a van from a
cell to one `courier:adjacentTo` it and names no coordinate (navigation-is-a-body-a-mover-and-a-move,
§4, in the courier's words). A road states its edges itself, segment to segment and lane to passing
place, since nothing can compute where a road goes; a grid is a road where every neighbour is an edge,
and what the coordinates imply is computed, never asserted by hand: this derivation writes, for every
pair of the world's cells one apart, |dx| + |dy| = 1, the edge each way, into `grid.derived.ttl` beside
the world, a world graph every reader reads as the world's own. Committed, and held to a fresh
derivation by `tests/test_layout.py`, as the society's topics are.

**Asserted wins.** A world any of whose documents states an edge is a road and is derived nothing: its
author said where one may drive, and a grid's completion would open the sand.

**Run before the world is judged.** `orexis-onboard` derives first and then asks `reading.check`;
`orexis-grid <world>` is this step alone.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pyoxigraph as ox

from agent.runtime import WORLD
from agent.store import answer, forget_graph, graphs_of, rows

from . import derived, reading
from .worlds import shown, world_dir, worlds

log = logging.getLogger("grid")

DERIVED = "grid.derived.ttl"
COURIER = "http://example.org/orexis/courier#"
OREXIS = "http://example.org/orexis#"

_CELLS_Q = f"SELECT ?cell ?x ?y WHERE {{ ?cell a <{COURIER}Cell> ; <{COURIER}x> ?x ; <{COURIER}y> ?y }} ORDER BY ?cell"
_EDGES_Q = f"ASK {{ ?cell <{COURIER}adjacentTo> ?other }}"


def derivation(world: str) -> Path:
    return world_dir(world) / DERIVED


def _asserted(here: Path) -> ox.Store:
    """The world in `here` as onboarding reads it, less this derivation's own document on disk, so a
    stale one is written over and never read as asserted."""
    store = reading.world(here)
    on_disk = (here / DERIVED).resolve().as_uri()
    if on_disk in graphs_of(store, WORLD, common=True):
        forget_graph(store, on_disk, revisions=None)
    return store


def _cells(store: ox.Store) -> list[tuple[str, int, int]]:
    return [(r["cell"], int(r["x"]), int(r["y"])) for r in rows(store, _CELLS_Q, graphs_of(store, reading.BELIEF, common=True))]


def applies(world: str) -> bool:
    """Whether `world` is a grid to complete: its cells state coordinates, and no document of its
    states an edge."""
    return applies_at(world_dir(world))


def applies_at(here: Path, store: ox.Store | None = None) -> bool:
    store = _asserted(here) if store is None else store
    stated = answer(store, _EDGES_Q, graphs_of(store, reading.BELIEF, common=True))
    return bool(_cells(store)) and not bool(stated["boolean"])


def derive(world: str) -> list[tuple[str, str, ox.NamedNode]]:
    """Every edge the coordinates imply, each way: (cell, courier:adjacentTo, neighbour), sorted."""
    return derive_at(world_dir(world))


def derive_at(here: Path) -> list[tuple[str, str, ox.NamedNode]]:
    store = _asserted(here)
    if not applies_at(here, store):
        return []
    cells = _cells(store)
    return sorted((a, COURIER + "adjacentTo", ox.NamedNode(b)) for a, ax, ay in cells for b, bx, by in cells
                  if abs(ax - bx) + abs(ay - by) == 1)


_HEADER = """GENERATED by `orexis-onboard` from this world's own documents — do not edit. The edges a grid's
coordinates imply, each way: two cells one apart, |dx| + |dy| = 1, are `courier:adjacentTo`, which is
what a drive reads (knowledge/domain/courier/adjacency.md). A world that states any edge itself is a
road, and is derived none."""


def derivation_text(world: str, statements=None) -> str:
    """The derived grid document for `world`, as `derive` would write it now."""
    statements = derive(world) if statements is None else statements
    return _text(statements)


def _text(statements) -> str:
    spoken = {s.rsplit("#", 1)[0] + "#" for s, _, _ in statements if "#" in s}
    prefixes = {"courier": COURIER, "orexis": OREXIS, **({"": spoken.pop()} if len(spoken) == 1 else {})}
    return derived.text(WORLD, statements, prefixes, _HEADER)


def write(world: str) -> Path | None:
    """Derive, and write what was derived beside the world where the world is a grid; the path, or
    None where the world states its own edges, when a derivation left behind is removed."""
    return write_at(world_dir(world))


def write_at(here: Path) -> Path | None:
    """`write`, for a world wherever it is — a test's copy of one among them."""
    statements = derive_at(here)
    path = here / DERIVED
    if not statements:
        if path.exists():
            path.unlink()
            log.info("removed %s: the world states its own edges", shown(path))
        return None
    path.write_text(_text(statements))
    log.info("  %d edges between %d cells", len(statements), len({s for s, _, _ in statements}))
    log.info("wrote %s", shown(path))
    return path


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    p = argparse.ArgumentParser(prog="orexis-grid",
                                description="Derive a grid world's adjacency from its cells' coordinates, into "
                                            "world/<world>/grid.derived.ttl — the step of orexis-onboard that needs nothing up.")
    p.add_argument("world", help="which world. Available: " + ", ".join(worlds()))
    args = p.parse_args()
    if write(args.world) is None:
        log.info("world %r states its own edges, or has no cells: nothing derived", args.world)


if __name__ == "__main__":
    main()
