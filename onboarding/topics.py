"""A topic's name: what onboarding derives of a society that states no filter (#836).

**A society states THAT, and a rule says WHICH.** A sensor publishes on a topic, an actuator takes
commands on one, an agent listens on one — the MQTT4SSN topic node, which both ends name — and
which filter pattern the topic goes by on the wire matters to nobody, only that both ends agree: the
argument that made a bucket `<world>-<agent>` by one function, stated in no document
(knowledge/decisions/series-and-bus-isolation.md). So the filter is derived, by the one `sh:rule`
in `onboarding/requirements.ttl` — `sensors/<client>/reading` for what a board publishes,
`sensors/<client>/command` for what it listens to, `actuators/<device>/command` for a device a
client hosts, `agents/<id>/inbox` for an agent, `people/<person>/inbox` for a person the translator
speaks for, with `people/<person>/says` and `people/<person>/hears` where they speak through a client of
their own — and a society of 2026-10-15 states no filter.

**Derived into a document, which every reader reads as any other.** The agent reads topics and
never imports onboarding, so the derivation reaches it the way every other fact does: `write` runs
the rule over the world's asserted documents and writes what it made to `society.derived.ttl`
beside the society, a society graph, which the agents, the simulator, `orexis-mqtt`'s ACL and
`orexis-firmware` read exactly as they read the society — none of them computes a name, and
every derived name is a line a reviewer reads in a diff (`onboarding.derived`). Committed, and
held to a fresh derivation by `tests/test_layout.py`, as the installation's allocation is.

**Asserted wins, derived completes.** The rule fills a topic that has no filter, so a filter a
world asserts is kept and the rule writes none for it; and what remains unnamed once the derived
document is in — a topic nothing publishes on or listens to — the requirement refuses.

**Run before the world is judged.** `orexis-onboard` derives first and then asks `reading.check`,
which reads the derived document on disk; a tool called alone reads what the last run wrote, and
refuses a world whose topics it has not named, since a renderer computes nothing. `orexis-topics
<world>` is this step alone, for an author with no series store or broker up to onboard against.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pyoxigraph as ox
import pyshacl
import rdflib

from agent.runtime import SOCIETY
from agent.store import NAMESPACES, forget_graph, graphs_of, rdflib_view

from . import derived, reading
from .worlds import world_dir, worlds

log = logging.getLogger("topics")

#  THE DERIVED SOCIETY DOCUMENT, beside the society. The name is for eyes, as every document's is: the
#  agent reads it by the kind it says. It is the one path onboarding knows, as the installation's
#  derivation is, since what it holds is what a fresh derivation would write.
DERIVED = "society.derived.ttl"
MQTT4SSN = "https://www.w3id.org/MQTT4SSN-Ontology#"
OREXIS = "http://example.org/orexis#"


def derivation(world: str) -> Path:
    return world_dir(world) / DERIVED


def derive(world: str) -> list[tuple[str, str, ox.NamedNode | ox.Literal]]:
    """Every statement the requirements' rules make of `world`'s asserted documents — each topic's
    filter, where the society states none — as (subject, predicate, object), sorted. The world is
    read as onboarding reads it, less the derived document on disk, so the derivation is made of
    the asserted documents alone and a stale one is written over."""
    here = world_dir(world)
    store = reading.world(here)
    on_disk = derivation(world).resolve().as_uri()
    if on_disk in graphs_of(store, SOCIETY):
        forget_graph(store, on_disk, revisions=None)
    data = rdflib_view(store, *graphs_of(store, reading.BELIEF, common=True))
    for label, iri in NAMESPACES.items():
        data.bind(label, iri, override=True, replace=True)
    requirements, _ = reading.shapes_of(store)
    before = set(data)
    #  THE RULES RUN HERE, and the report is nobody's: what is judged is the world with the derived
    #  document in, by `reading.check`. No vocabulary is mixed in, since pyshacl would mix it into the
    #  data in place and the diff would carry it.
    pyshacl.validate(data, shacl_graph=requirements, advanced=True, inplace=True)
    return [(s, p, _term(o)) for s, p, o in sorted((str(s), str(p), o) for s, p, o in set(data) - before)]


def _term(o) -> ox.NamedNode | ox.Literal:
    return ox.NamedNode(str(o)) if isinstance(o, rdflib.URIRef) else ox.Literal(str(o))


_HEADER = """GENERATED by `orexis-onboard` from this world's own documents — do not edit. The filter each topic is
named by, where the society states none: by the rule in onboarding/requirements.ttl, one convention
for every world — sensors/<client>/reading for what a board publishes, sensors/<client>/command for
what it listens to, actuators/<device>/command, agents/<agent>/inbox, people/<person>/inbox, and
people/<person>/says and /hears for a client a person speaks through. A filter the society asserts
itself is kept, and wins (knowledge/domain/onboarding/requirement.md)."""


def derivation_text(world: str, statements=None) -> str:
    """The derived society document for `world`, as `derive` would write it now."""
    statements = derive(world) if statements is None else statements
    spoken = {s.rsplit("#", 1)[0] + "#" for s, _, _ in statements if "#" in s}
    prefixes = {"mqtt4ssn": MQTT4SSN, "orexis": OREXIS, **({"": spoken.pop()} if len(spoken) == 1 else {})}
    return derived.text(SOCIETY, statements, prefixes, _HEADER)


def write(world: str) -> Path:
    """Derive, and write what was derived beside the society; the path."""
    statements = derive(world)
    path = derivation(world)
    path.write_text(derivation_text(world, statements))
    for subject, predicate, obj in statements:
        if predicate == MQTT4SSN + "hasFilterPattern":
            log.info("  named %s  %s", subject.rsplit("#", 1)[-1].removesuffix("_filter"), obj.value)
    log.info("wrote %s", path.relative_to(world_dir(world).parent.parent) if path.is_relative_to(world_dir(world).parent.parent) else path)
    return path


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    p = argparse.ArgumentParser(prog="orexis-topics",
                                description="Name a world's topics by onboarding's one convention, into "
                                            "world/<world>/society.derived.ttl — the step of orexis-onboard that needs nothing up.")
    p.add_argument("world", help="which world. Available: " + ", ".join(worlds()))
    args = p.parse_args()
    if reading.BUS not in reading.premises(world_dir(args.world)):
        raise SystemExit(f"world {args.world!r} names no mqtt4ssn:Broker — it has no bus, and no topic to name")
    write(args.world)


if __name__ == "__main__":
    main()
