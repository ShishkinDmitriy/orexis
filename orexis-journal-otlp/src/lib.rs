//! THE JOURNAL, OVER OTLP: the half of the pair that keeps house. `orexis-journal/` keeps every activity the agent's
//! packages end in its journal; this ships them to whoever traces the agent, on a timer, reading them there and
//! hearing nothing. It knows no package's words.
//!
//! WHAT IS SHIPPED IS WHAT THE JOURNAL HOLDS AND THIS HAS NOT SENT: every `prov:Activity` entry with no
//! `orexis:shippedTo` this endpoint. AN ACTIVITY IS A SPAN, named by its class; one begun inside another
//! (`dcterms:isPartOf`) is its child, and a trace is an activity begun inside none with everything inside it; each
//! event said in it is an event on the span, at the instant it was said and carrying its name (`prov.entity`); what
//! started it is the span's `orexis.trigger`, each trigger's class; and WHAT CAUSED IT IS A LINK - where a thing that
//! started it was generated by another activity (`prov:wasGeneratedBy`), the span links to that activity's, a link
//! per trigger saying which: its class and its name, the name the mark on the causing span carries. So the
//! dependencies between packages are drawn, and which event of the one began the other is read off the link. Its start is the agent's instant and
//! its length the real seconds it took (`orexis:tookS`).
//!
//! SHIPPED, THEN MARKED: an activity is marked `orexis:shippedTo` only once the tracer accepted the POST that carried
//! it. One that refuses is said in the log once until it answers again, and what it was not told stays unshipped in
//! the journal until the journal's window sweeps it - the hot record is bounded whether or not anything ships.
//!
//! OTLP'S JSON OVER HTTP, written here rather than by the OpenTelemetry SDK: one POST of a documented shape to
//! `$OTLP_ENDPOINT/v1/traces` every `OTLP_INTERVAL_S` of the agent's time, ten seconds where nothing says, made off
//! the agent's own threads, so a tracer slow or away never holds the mind.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;
use std::time::Duration;

use oxigraph::model::{Literal, NamedNode};
use serde_json::{Value, json};

use orexis::events::triple;
use orexis::task::{Handed, Package, Task};
use orexis_journal::journal::{ACTIVITY, Journal};

/// Where the tracer is, told as environment: OTLP's HTTP endpoint, `/v1/traces` beneath it.
pub const ENDPOINT: &str = "OTLP_ENDPOINT";
/// How often what is kept is shipped, in the agent's seconds, told as environment.
pub const INTERVAL: &str = "OTLP_INTERVAL_S";
/// How often, where the environment says nothing.
pub const INTERVAL_S: f64 = 10.0;
/// An activity shipped says to which cold store, so two may each have their own.
pub const SHIPPED_TO: &str = "http://example.org/orexis#shippedTo";

/// How a batch of spans reaches the tracer: the body of one POST, and whether it was accepted.
pub type Send = Arc<dyn Fn(String) -> bool + std::marker::Send + Sync>;

/// Where the agent is traced and how often it ships, as its deployment says.
#[derive(Clone, Debug, PartialEq)]
pub struct Tracing {
    pub endpoint: String,
    pub every_s: f64,
}

/// What is shipped and where, handed outside by whoever runs the agent, where the deployment traces it.
pub struct Ships {
    pub journal: Arc<Journal>,
    pub endpoint: String,
    pub every_s: f64,
}

fn rows(journal: &Journal, text: &str) -> Vec<BTreeMap<String, String>> {
    let Ok((_, body)) = orexis_journal::journal::answer(&journal.store, text) else {
        return Vec::new();
    };
    let Ok(value) = serde_json::from_slice::<Value>(&body) else {
        return Vec::new();
    };
    value["results"]["bindings"]
        .as_array()
        .map(|bindings| {
            bindings
                .iter()
                .map(|b| {
                    b.as_object()
                        .map(|o| {
                            o.iter()
                                .filter_map(|(k, v)| Some((k.clone(), v["value"].as_str()?.to_string())))
                                .collect()
                        })
                        .unwrap_or_default()
                })
                .collect()
        })
        .unwrap_or_default()
}

/// The hex of a UUID's URN, its last `n` digits.
fn hex(node: &str, n: usize) -> String {
    let digits: String = node.chars().filter(|c| c.is_ascii_hexdigit()).collect();
    format!("{:0>n$}", &digits[digits.len().saturating_sub(n)..])
}

/// The local name of an IRI: what follows its last `#` or `/`.
fn local(iri: &str) -> &str {
    iri.rsplit(['#', '/']).next().unwrap_or(iri)
}

/// What a span or a link says started the activity: the class of each trigger.
pub const TRIGGER: &str = "orexis.trigger";
/// The name of an event, on its mark and on the link of what it caused.
pub const ENTITY: &str = "prov.entity";

fn text(key: &str, value: &str) -> Value {
    json!({"key": key, "value": {"stringValue": value}})
}

/// An instant as OTLP says it: nanoseconds of the Unix epoch.
fn nanos(at: &str) -> u128 {
    at.parse::<oxsdatatypes::DateTime>()
        .ok()
        .and_then(|t| t.checked_sub("1970-01-01T00:00:00Z".parse::<oxsdatatypes::DateTime>().ok()?))
        .map(|d| (orexis::clock::seconds_of(d).max(0.0) * 1e9) as u128)
        .unwrap_or(0)
}

/// EVERY ACTIVITY THE JOURNAL HOLDS THAT `endpoint` WAS NOT SENT, as one OTLP body, and the activities in it; None
/// where there is none.
pub fn batch(journal: &Journal, agent: &str, endpoint: &str) -> Option<(String, Vec<String>)> {
    let unshipped = rows(
        journal,
        &format!(
            "SELECT ?a ?kind ?start ?took WHERE {{ GRAPH ?a {{ ?a a <{ACTIVITY}> , ?kind ; \
             <http://www.w3.org/ns/prov#startedAtTime> ?start ; <http://example.org/orexis#tookS> ?took . \
             FILTER(?kind != <{ACTIVITY}>) FILTER NOT EXISTS {{ ?a <{SHIPPED_TO}> \"{endpoint}\" }} }} }} ORDER BY ?start ?a"
        ),
    );
    if unshipped.is_empty() {
        return None;
    }
    //  WHAT EACH ACTIVITY WAS BEGUN INSIDE, over everything the journal holds: a trace is named for the outermost.
    let parents: BTreeMap<String, String> = rows(
        journal,
        "SELECT ?a ?p WHERE { GRAPH ?a { ?a <http://purl.org/dc/terms/isPartOf> ?p } }",
    )
    .into_iter()
    .filter_map(|r| Some((r.get("a")?.clone(), r.get("p")?.clone())))
    .collect();
    let root = |a: &str| -> String {
        let (mut at, mut seen) = (a.to_string(), BTreeSet::new());
        while let Some(parent) = parents.get(&at) {
            if !seen.insert(at.clone()) {
                break;
            }
            at = parent.clone();
        }
        at
    };
    let mut triggers: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for r in rows(
        journal,
        "SELECT ?a ?x WHERE { GRAPH ?a { ?a <http://www.w3.org/ns/prov#wasStartedBy> ?x } } ORDER BY ?a ?x",
    ) {
        if let (Some(a), Some(x)) = (r.get("a"), r.get("x")) {
            triggers.entry(a.clone()).or_default().push(x.clone());
        }
    }
    //  WHAT GENERATED EACH THING, the class an event said it is and the instant it was said at.
    let mut generated: BTreeMap<String, String> = BTreeMap::new();
    let mut kinds: BTreeMap<String, String> = BTreeMap::new();
    let mut said: BTreeMap<String, Vec<(String, String, Option<String>)>> = BTreeMap::new();
    for r in rows(
        journal,
        "SELECT ?x ?c ?k ?t WHERE { GRAPH ?c { ?x <http://www.w3.org/ns/prov#wasGeneratedBy> ?c \
         OPTIONAL { ?x a ?k } OPTIONAL { ?x <http://www.w3.org/ns/prov#generatedAtTime> ?t } } } ORDER BY ?c ?t ?x",
    ) {
        if let (Some(x), Some(c)) = (r.get("x"), r.get("c")) {
            generated.insert(x.clone(), c.clone());
            if let Some(kind) = r.get("k") {
                kinds.insert(x.clone(), kind.clone());
                said.entry(c.clone())
                    .or_default()
                    .push((x.clone(), local(kind).to_string(), r.get("t").cloned()));
            }
        }
    }
    //  WHAT A TRIGGER IS CALLED: the class it said it is, or its own name where it said none, as a graph says none.
    let called = |x: &str| {
        kinds
            .get(x)
            .map_or_else(|| local(x).to_string(), |k| local(k).to_string())
    };
    let mut spans = Vec::new();
    let mut shipped = Vec::new();
    for r in &unshipped {
        let (Some(a), Some(kind), Some(start), Some(took)) = (r.get("a"), r.get("kind"), r.get("start"), r.get("took"))
        else {
            continue;
        };
        let begins = nanos(start);
        let ends = begins + (took.parse::<f64>().unwrap_or(0.0).max(0.0) * 1e9) as u128;
        let started_by = triggers.get(a).cloned().unwrap_or_default();
        let mut attributes = vec![text("orexis.agent", agent)];
        if !started_by.is_empty() {
            //  ONE ATTRIBUTE, since a span's keys are unique: every trigger's class, in the order of their names.
            let named: Vec<String> = started_by.iter().map(|x| called(x)).collect();
            attributes.push(text(TRIGGER, &named.join(" ")));
        }
        //  A LINK PER TRIGGER ANOTHER ACTIVITY GENERATED, saying which: its class and its name, the name the mark on
        //  the causing span carries.
        let links: Vec<Value> = started_by
            .iter()
            .filter_map(|x| Some((x, generated.get(x)?)))
            .filter(|(_, cause)| *cause != a)
            .map(|(x, cause)| {
                json!({
                    "traceId": hex(&root(cause), 32),
                    "spanId": hex(cause, 16),
                    "attributes": [text(TRIGGER, &called(x)), text(ENTITY, x)],
                })
            })
            .collect();
        let events: Vec<Value> = said
            .get(a)
            .map(|events| {
                events
                    .iter()
                    .map(|(x, kind, at)| {
                        let at = at.as_deref().map_or(begins, nanos);
                        json!({"timeUnixNano": at.to_string(), "name": kind, "attributes": [text(ENTITY, x)]})
                    })
                    .collect()
            })
            .unwrap_or_default();
        spans.push(json!({
            "traceId": hex(&root(a), 32),
            "spanId": hex(a, 16),
            "parentSpanId": parents.get(a).map(|p| hex(p, 16)).unwrap_or_default(),
            "name": local(kind),
            "kind": 1,
            "startTimeUnixNano": begins.to_string(),
            "endTimeUnixNano": ends.to_string(),
            "attributes": attributes,
            "events": events,
            "links": links,
        }));
        shipped.push(a.clone());
    }
    let body = json!({"resourceSpans": [{
        "resource": {"attributes": [text("service.name", agent)]},
        "scopeSpans": [{"scope": {"name": "orexis"}, "spans": spans}],
    }]});
    Some((body.to_string(), shipped))
}

/// Say of each of `activities` that `endpoint` was sent it.
pub fn mark(journal: &Journal, activities: &[String], endpoint: &str) {
    for activity in activities {
        let Ok(node) = NamedNode::new(activity.as_str()) else {
            continue;
        };
        let said = triple(node.clone(), SHIPPED_TO, Literal::new_simple_literal(endpoint));
        if let Err(e) = journal.add(&node, vec![said]) {
            log::warn!("the journal refused to say an activity was shipped: {e}");
        }
    }
}

/// Ship what the journal holds unshipped, by `send`, and mark what was accepted; how many activities went.
pub fn ship(journal: &Journal, agent: &str, endpoint: &str, send: &Send) -> usize {
    let Some((body, activities)) = batch(journal, agent, endpoint) else {
        return 0;
    };
    if !send(body) {
        return 0;
    }
    mark(journal, &activities, endpoint);
    activities.len()
}

/// What the environment says of the tracer: its endpoint and how often to ship, or None where it names no endpoint.
pub fn from_environment(env: &dyn Fn(&str) -> Option<String>) -> Option<Tracing> {
    let endpoint = env(ENDPOINT)
        .map(|e| e.trim_end_matches('/').to_string())
        .filter(|e| !e.is_empty())?;
    let every_s = env(INTERVAL)
        .and_then(|s| s.parse::<f64>().ok())
        .filter(|s| *s > 0.0)
        .unwrap_or(INTERVAL_S);
    Some(Tracing { endpoint, every_s })
}

/// POST each body to `endpoint`'s traces, and say whether it was accepted.
pub fn post(endpoint: &str) -> Send {
    let url = format!("{endpoint}/v1/traces");
    let agent = ureq::AgentBuilder::new().timeout(Duration::from_secs(2)).build();
    let refused = std::sync::atomic::AtomicBool::new(false);
    Arc::new(move |body| {
        match agent
            .post(&url)
            .set("Content-Type", "application/json")
            .send_string(&body)
        {
            Ok(_) => {
                refused.store(false, std::sync::atomic::Ordering::Relaxed);
                true
            }
            Err(e) => {
                if !refused.swap(true, std::sync::atomic::Ordering::Relaxed) {
                    log::warn!("the tracer at {url} refused the agent's spans, and they stay unshipped: {e}");
                }
                false
            }
        }
    })
}

inventory::submit! { Package { name: "journal-otlp", start } }

/// THE SHIPPER'S START: where it is handed a journal and an endpoint, its task; and none otherwise.
fn start(handed: &Handed) -> Result<Option<Task>, orexis::Error> {
    let Some(ships) = handed.outside.take::<Ships>() else {
        return Ok(None);
    };
    let send = post(&ships.endpoint);
    Ok(Some(Box::pin(task(handed.clone(), ships, send))))
}

/// THE SHIPPER'S TASK: every stretch of the agent's time it ships what the journal holds unshipped, off the agent's
/// threads, and once more as the run ends.
async fn task(handed: Handed, ships: Ships, send: Send) -> Result<(), orexis::Error> {
    let agent = handed.id.clone();
    let shipping = |journal: Arc<Journal>, endpoint: String, send: Send, agent: String| async move {
        let _ = tokio::task::spawn_blocking(move || ship(&journal, &agent, &endpoint, &send)).await;
    };
    loop {
        let due = handed
            .clock
            .now()
            .checked_add_day_time_duration(orexis::clock::seconds(ships.every_s));
        let over = tokio::select! {
            biased;
            _ = handed.stopped() => true,
            _ = handed.sleep_until(due) => false,
        };
        shipping(
            ships.journal.clone(),
            ships.endpoint.clone(),
            send.clone(),
            agent.clone(),
        )
        .await;
        if over {
            break;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Mutex;

    use orexis::events::{double, instant, mint, typed};
    use oxigraph::model::Triple;

    const PLANNING: &str = "http://example.org/orexis/planning#Planning";
    const SEARCHING: &str = "http://example.org/test#Searching";
    const REVISING: &str = "http://example.org/orexis/belief#Revising";
    const REVISED: &str = "http://example.org/orexis/belief#Revised";
    const TRACER: &str = "http://127.0.0.1:4318";

    fn at(text: &str) -> oxsdatatypes::DateTime {
        text.parse().unwrap()
    }

    fn journal() -> Arc<Journal> {
        Arc::new(Journal::new(600.0, Arc::new(|| at("2026-11-10T12:00:00Z"))).unwrap())
    }

    /// An activity as `orexis-journal/` keeps it.
    fn kept(journal: &Journal, kind: &str, started_by: &[&NamedNode], inside: Option<&NamedNode>) -> NamedNode {
        let a = mint();
        let mut triples: Vec<Triple> = vec![
            typed(a.clone(), kind),
            typed(a.clone(), ACTIVITY),
            triple(
                a.clone(),
                "http://www.w3.org/ns/prov#startedAtTime",
                instant(at("2026-11-10T12:00:00Z")),
            ),
            triple(a.clone(), "http://example.org/orexis#tookS", double(0.5)),
        ];
        for x in started_by {
            triples.push(triple(
                a.clone(),
                "http://www.w3.org/ns/prov#wasStartedBy",
                (*x).clone(),
            ));
        }
        if let Some(parent) = inside {
            triples.push(triple(a.clone(), "http://purl.org/dc/terms/isPartOf", parent.clone()));
        }
        journal
            .record(&a, triples, Some(at("2026-11-10T12:00:00Z")), false)
            .unwrap();
        a
    }

    fn generated(journal: &Journal, by: &NamedNode, kind: &str) -> NamedNode {
        let x = mint();
        journal
            .add(
                by,
                vec![
                    triple(x.clone(), "http://www.w3.org/ns/prov#wasGeneratedBy", by.clone()),
                    typed(x.clone(), kind),
                    triple(
                        x.clone(),
                        "http://www.w3.org/ns/prov#generatedAtTime",
                        instant(at("2026-11-10T12:00:00.25Z")),
                    ),
                ],
            )
            .unwrap();
        x
    }

    fn spans(body: &str) -> Vec<Value> {
        let body: Value = serde_json::from_str(body).unwrap();
        body["resourceSpans"][0]["scopeSpans"][0]["spans"]
            .as_array()
            .unwrap()
            .clone()
    }

    /// What the journal keeps is what is shipped: an activity a span, one begun inside another its child in one
    /// trace, an event said in it an event on the span at its own instant, and what caused it a link to the span
    /// that generated what started it, in a trace of its own, saying which event that was.
    #[test]
    fn what_the_journal_keeps_is_shipped_as_spans_with_their_children_and_their_causes() {
        let journal = journal();
        let revising = kept(&journal, REVISING, &[], None);
        let revised = generated(&journal, &revising, REVISED);
        let planning = kept(&journal, PLANNING, &[&revised], None);
        let searching = kept(&journal, SEARCHING, &[], Some(&planning));
        let (body, shipped) = batch(&journal, "fern", TRACER).unwrap();
        assert_eq!(shipped.len(), 3);
        let spans = spans(&body);
        let by = |name: &str| spans.iter().find(|s| s["name"] == name).unwrap().clone();
        let (r, p, s) = (by("Revising"), by("Planning"), by("Searching"));
        assert_eq!(p["spanId"], json!(hex(planning.as_str(), 16)));
        assert_eq!(s["parentSpanId"], p["spanId"], "begun inside the planning");
        assert_eq!(s["traceId"], p["traceId"], "and in its trace");
        assert_ne!(r["traceId"], p["traceId"], "what caused it is another trace");
        assert_eq!(
            p["links"],
            json!([{
                "traceId": r["traceId"],
                "spanId": r["spanId"],
                "attributes": [text(TRIGGER, "Revised"), text(ENTITY, revised.as_str())],
            }]),
            "the link says which event of the revising began the planning"
        );
        let mark = &r["events"][0];
        assert_eq!(mark["name"], "Revised");
        assert_eq!(
            mark["attributes"],
            json!([text(ENTITY, revised.as_str())]),
            "and the mark on the revising carries the same name"
        );
        let after = mark["timeUnixNano"].as_str().unwrap().parse::<u128>().unwrap()
            - r["startTimeUnixNano"].as_str().unwrap().parse::<u128>().unwrap();
        assert!(
            after.abs_diff(250_000_000) < 1_000,
            "at the instant it was said, not the span's start: {after}"
        );
        assert_eq!(p["traceId"].as_str().unwrap().len(), 32);
        assert_eq!(p["spanId"].as_str().unwrap().len(), 16);
        let took = p["endTimeUnixNano"].as_str().unwrap().parse::<u128>().unwrap()
            - p["startTimeUnixNano"].as_str().unwrap().parse::<u128>().unwrap();
        assert_eq!(took, 500_000_000, "as long as it really took");
        let triggers: Vec<&Value> = p["attributes"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|a| a["key"] == TRIGGER)
            .collect();
        assert_eq!(
            triggers,
            [&text(TRIGGER, "Revised")],
            "one attribute, the trigger's class"
        );
        let _ = searching;
    }

    /// An activity is marked shipped only where the tracer accepted it, and is not shipped twice; what a tracer
    /// refused stays in the journal for the next time.
    #[test]
    fn an_activity_is_shipped_once_and_stays_unshipped_where_the_tracer_refused() {
        let journal = journal();
        kept(&journal, PLANNING, &[], None);
        let sent: Arc<Mutex<Vec<String>>> = Arc::default();
        let refusing: Send = Arc::new(|_| false);
        assert_eq!(ship(&journal, "fern", TRACER, &refusing), 0);
        let got = sent.clone();
        let accepting: Send = Arc::new(move |body| {
            got.lock().unwrap().push(body);
            true
        });
        assert_eq!(
            ship(&journal, "fern", TRACER, &accepting),
            1,
            "refused before, shipped now"
        );
        assert_eq!(ship(&journal, "fern", TRACER, &accepting), 0, "and not again");
        assert_eq!(sent.lock().unwrap().len(), 1);
        kept(&journal, SEARCHING, &[], None);
        assert_eq!(ship(&journal, "fern", TRACER, &accepting), 1, "only what came since");
        assert_eq!(
            ship(&journal, "fern", "http://another:4318", &accepting),
            2,
            "another cold store has its own"
        );
    }

    #[test]
    fn the_endpoint_and_the_interval_are_the_environments() {
        let env = |k: &str| match k {
            ENDPOINT => Some("http://127.0.0.1:4318/".to_string()),
            INTERVAL => Some("30".to_string()),
            _ => None,
        };
        assert_eq!(
            from_environment(&env),
            Some(Tracing {
                endpoint: "http://127.0.0.1:4318".to_string(),
                every_s: 30.0
            })
        );
        let only = |k: &str| (k == ENDPOINT).then(|| "http://127.0.0.1:4318".to_string());
        assert_eq!(from_environment(&only).unwrap().every_s, INTERVAL_S);
        assert_eq!(from_environment(&|_| None), None);
    }
}
