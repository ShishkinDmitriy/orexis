//! THE JOURNAL, OVER OTLP: the half of the pair that keeps house. `orexis-journal/` keeps every activity the agent's
//! packages end in its journal; this ships them to whoever traces the agent, on a timer, reading them there and
//! hearing nothing. It knows no package's words.
//!
//! WHAT IS SHIPPED IS WHAT THE JOURNAL HOLDS AND THIS HAS NOT SENT: every `prov:Activity` entry with no
//! `orexis:shippedTo` this endpoint. AN ACTIVITY IS A SPAN, named by its class; one begun inside another
//! (`dcterms:isPartOf`) is its child, and a trace is an activity begun inside none with everything inside it; each
//! event said in it is an event on the span, at the instant it was said and carrying its name (`prov.entity`); what
//! started it is the span's `orexis.trigger`, each trigger's class; and WHAT CAUSED IT IS A LINK - where a thing that
//! started it was generated by another activity (`prov:wasGeneratedBy`), the span links to that activity's, a link
//! per trigger saying which: its class and its name, the name the mark on the causing span carries. So the
//! dependencies between packages are drawn, and which event of the one began the other is read off the link. Its start is the agent's instant and
//! its length the real seconds it took (`orexis:tookS`).
//!
//! SHIPPED, THEN MARKED: an activity is marked `orexis:shippedTo` only once the tracer accepted the POST that carried
//! it. One that refuses is said in the log once until it answers again, and what it was not told stays unshipped in
//! the journal until the journal's window sweeps it - the hot record is bounded whether or not anything ships.
//!
//! OTLP'S JSON OVER HTTP, written here rather than by the OpenTelemetry SDK: one POST of a documented shape to
//! `/v1/traces` beneath the url of the tracer the recorder's role names, where the world's deployment says it answers, as often as the role says and every ten of the agent's seconds where it says nothing, made off
//! the agent's own threads, so a tracer slow or away never holds the mind.
//!
//! - `ships`: what is shipped and where, and each batch read, posted and marked;
//! - the start, below the modules, and nothing else: what to ship made, and the task that ships it on a timer.

use std::sync::Arc;

use orexis::task::{Handed, Package};
use orexis_journal::Traced;

mod ships;

pub use ships::{SHIPPED_TO, Send, Ships, batch, mark, post, ship};

inventory::submit! { Package { name: "journal-otlp", documents: &[], start } }

/// ITS START, which every package this binary holds is given: it keeps house for the journal, so it joins where the
/// journal did AND THE RECORDER'S ROLE NAMES A TRACER the world says where to reach, and where the role names none
/// its start ends there. Joined, it says it has started, which waits for the journal's start; checked, it ends there;
/// otherwise it takes what a test hands it to ship or the journal handed on, and what follows is ITS TASK, which every
/// stretch of the agent's time ships what the journal holds unshipped, off the agent's threads, and once more as the
/// run ends: where to ship is the world's word, and how often the role's.
fn start(handed: Handed) -> orexis::task::Starting {
    Box::pin(async move {
        //  IT RUNS WHERE THE RECORDER'S ROLE NAMES ITS SERVICE.
        if !handed.plays(&[orexis_journal::ROLE])? {
            return Ok(());
        }
        let recorder = orexis_journal::Recorder::new(&handed.store)?;
        if recorder.traced_by.is_none() {
            return Ok(());
        }
        //  ITS CORE IS MADE ONCE EVERY PACKAGE HAS MADE ITS OWN, so the journal it keeps house for is handed on.
        handed.started("journal-otlp").await;
        if handed.checking().is_some() {
            return Ok(());
        }
        //  HANDED ONE, by a test that ships to its own endpoint, it ships that; otherwise it makes its own.
        let ships = match handed.provided.take::<Ships>() {
            Some(ships) => ships,
            None => {
                let (Some(endpoint), Some(journal)) = (recorder.traced_by, handed.provided.read::<Traced>()) else {
                    return Ok(());
                };
                Ships {
                    journal: journal.0,
                    endpoint,
                    every_s: recorder.traced_every_s,
                }
            }
        };
        log::info!(
            "{} ships its activities as spans to {} every {}s",
            handed.id,
            ships.endpoint,
            ships.every_s
        );
        let send = post(&ships.endpoint);
        let agent = handed.id.clone();
        let shipping = |journal: Arc<orexis_journal::Journal>, endpoint: String, send: Send, agent: String| async move {
            let _ = tokio::task::spawn_blocking(move || ship(&journal, &agent, &endpoint, &send)).await;
        };
        loop {
            let due = handed
                .clock
                .now()
                .checked_add_day_time_duration(orexis::clock::seconds(ships.every_s));
            let over = tokio::select! {
                biased;
                _ = handed.stopped() => true,
                _ = handed.sleep_until(due) => false,
            };
            shipping(
                ships.journal.clone(),
                ships.endpoint.clone(),
                send.clone(),
                agent.clone(),
            )
            .await;
            if over {
                break;
            }
        }
        Ok(())
    })
}
